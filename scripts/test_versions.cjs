'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const client = read('clients/namedP/VERSION').trim();
const server = read('cmd/namedicmp/main.go').match(/const version = "([^"]+)"/)[1];
assert.match(client, /^\d+\.\d+\.\d+-alpha$/);
assert.match(server, /^\d+\.\d+\.\d+$/, 'server release must have a stable version');
assert.equal(read('install.sh').match(/^MANAGER_VERSION=(.+)$/m)[1], server);
assert.equal(JSON.parse(read('package.json')).version, server);
assert.equal(JSON.parse(read('package-lock.json')).version, server);
assert.ok(read('internal/panel/panel.go').includes('"version": "' + server + '"'));
assert.ok(read('internal/panel/web/index.html').includes(server + ' / STABLE'));
assert.notEqual(client, server, 'initial client version must be independent from server');
assert.equal(read('clients/namedP/namedP.csproj').match(/<Version>([^<]+)<\/Version>/)[1], client);
assert.equal(read('cmd/namedp-engine/main.go').match(/const version = "([^"]+)"/)[1], client);
assert.equal(read('clients/namedP/app.manifest').match(/assemblyIdentity version="([^"]+)"/)[1], client.split('-')[0] + '.0');
assert.ok(fs.existsSync(path.join(root, `docs/RELEASE-namedp-v${client}.md`)));
assert.ok(fs.existsSync(path.join(root, `docs/RELEASE-v${server}.md`)));
assert.ok(read('.github/workflows/namedp.yml').includes("tags: ['namedp-v*']"));
assert.ok(read('.github/workflows/build.yml').includes("tags: ['v*']"));
assert.ok(!read('.github/workflows/namedp.yml').includes('gh release create v0.3.0'));
console.log(`Independent release versions verified: namedICMP ${server}, namedP ${client}`);
